"""Generate pinned Unicode 16.0.0 canonical decomposition, combining and Cf data."""
from pathlib import Path
import argparse, unicodedata as u
parser=argparse.ArgumentParser(); parser.add_argument('--check',action='store_true'); args=parser.parse_args()
if u.unidata_version != '16.0.0': raise SystemExit('Requires Python with Unicode 16.0.0')
lines=['/* Generated by scripts/generate-unicode.py; Unicode 16.0.0. See UNICODE-LICENSE.txt. */',
 '#include "rmd_unicode_data.h"']
for name,prop in [('combining',lambda c:u.combining(c)),('format',lambda c:int(u.category(c)=='Cf'))]:
 ranges=[]
 for cp in range(0x110000):
  v=prop(chr(cp))
  if not v: continue
  if ranges and ranges[-1][1]+1==cp and ranges[-1][2]==v: ranges[-1][1]=cp
  else: ranges.append([cp,cp,v])
 lines.append(f'const rmd_unicode_range rmd_{name}[] = {{')
 lines.extend(f'    {{{a}, {b}, {v}}},' for a,b,v in ranges); lines.append('};')
 lines.append(f'const size_t rmd_{name}_count = sizeof rmd_{name} / sizeof *rmd_{name};')
lines.append('const rmd_decomposition rmd_decompositions[] = {')
for cp in range(0x110000):
 if 0xac00<=cp<=0xd7a3: continue
 s=u.normalize('NFD',chr(cp))
 if s==chr(cp): continue
 parts=list(map(ord,s)); assert len(parts)<=4
 lines.append('    {%d, {%s}, %d},'%(cp,', '.join(map(str,parts)),len(parts)))
lines.append('};')
lines.append('const size_t rmd_decompositions_count = sizeof rmd_decompositions / sizeof *rmd_decompositions;')
text='\n'.join(lines)+'\n'; path=Path(__file__).resolve().parents[1]/'src/rmd_unicode_data.c'
if args.check:
 if path.read_text()!=text: raise SystemExit('Unicode tables differ')
else: path.write_text(text)
