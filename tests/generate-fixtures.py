"""Generate original synthetic ZIP fixtures and libFuzzer seeds (stdlib only)."""
from pathlib import Path
from cases import zip_bytes
import struct as s, zlib, argparse
p=Path(__file__).parent
valid=[('stored',zip_bytes([('doc.content',b'original fixture',0)]),0),
 ('deflated',zip_bytes([('doc.content',b'original fixture '*100,8)]),0),
 ('descriptor',zip_bytes([('doc.content',b'descriptor',8)],descriptor=1),0),
 ('signed_descriptor',zip_bytes([('doc.content',b'descriptor',8)],descriptor=2),0),
 ('local_padding',zip_bytes([('doc.content',b'padding',0)],local_extra=b'\xfe\xca\x00\x00\0'),0)]
# CRC equal to descriptor signature exercises unsigned-descriptor disambiguation.
def crc_payload(target):
 base=zlib.crc32(bytes(4)); basis={}
 for i in range(32):
  value=zlib.crc32((1<<i).to_bytes(4,'little'))^base; mask=1<<i
  while value:
   bit=value.bit_length()-1
   if bit not in basis: basis[bit]=(value,mask); break
   value^=basis[bit][0]; mask^=basis[bit][1]
 value=target^base; result=0
 while value:
  bit=value.bit_length()-1; value^=basis[bit][0]; result^=basis[bit][1]
 data=result.to_bytes(4,'little'); assert zlib.crc32(data)==target; return data
for descriptor in (1,2):
 valid.append((f'magic_crc_{descriptor}',zip_bytes([('doc.content',crc_payload(0x08074b50),0)],descriptor=descriptor),0))
fixtures=valid+[
 ('zip64_central',zip_bytes([('doc.content',b'z',0)],central_extra=b'\x01\0\0\0'),22),
 ('zip64_local',zip_bytes([('doc.content',b'z',0)],local_extra=b'\x01\0\0\0'),22),
 ('bad_extra',zip_bytes([('doc.content',b'z',0)],local_extra=b'\xfe\xca\xff\xff'),10),
 ('empty',zip_bytes([]),6), ('hostile',zip_bytes([('../escape',b'z',0)]),4)]
# Same compressed stream, false uncompressed declarations in both headers.
base=valid[1][1]; directory=s.unpack_from('<I',base,len(base)-6)[0]
for label,size in [('short',0),('long',1601),('physical',0xffffffff)]:
 b=bytearray(base); s.pack_into('<I',b,22,size); s.pack_into('<I',b,directory+24,size)
 fixtures.append((label,bytes(b),10))
# Trailing compressed byte is not another stream or padding we may ignore.
b=bytearray(base); old_size=s.unpack_from('<I',b,18)[0]; b[directory:directory]=b'\0'
s.pack_into('<I',b,18,old_size+1); s.pack_into('<I',b,directory+1+20,old_size+1); s.pack_into('<I',b,len(b)-6,directory+1)
fixtures.append(('trailing_deflate',bytes(b),10))
lines=['/* Generated by tests/generate-fixtures.py; synthetic payloads only. */', '#include <rmdoc/rmdoc.h>']
for name,data,expected in fixtures:
 lines.append(f'static const uint8_t fixture_{name}[] = {{')
 for i in range(0,len(data),16): lines.append('    '+', '.join(f'0x{x:02x}' for x in data[i:i+16])+',')
 lines.append('};')
lines.append('static const struct { const char *name; const uint8_t *data; size_t size; rmd_status expected; } fixtures[] = {')
for name,data,expected in fixtures: lines.append(f'    {{"{name}", fixture_{name}, sizeof fixture_{name}, {expected}}},')
lines.append('};')
text='\n'.join(lines)+'\n'
parser=argparse.ArgumentParser(); parser.add_argument('--check',action='store_true'); args=parser.parse_args()
if args.check:
 assert (p/'fixtures.h').read_text()==text
 for name,data,_ in valid: assert (p/'fuzz-seeds'/name).read_bytes()==data
else:
 (p/'fixtures.h').write_text(text); (p/'fuzz-seeds').mkdir(exist_ok=True)
 for name,data,_ in valid: (p/'fuzz-seeds'/name).write_bytes(data)
